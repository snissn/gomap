#!/usr/bin/env python3
"""Offline Python/hash/constructor contract checks. Never executes Go."""
import ast
import hashlib
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]


def require(value, message):
    if not value:
        raise AssertionError(message)


def main():
    for path in HERE.glob("*.py"):
        ast.parse(path.read_text(), filename=str(path))
    accepted = json.loads((HERE / "accepted-files.json").read_text())
    require(accepted["base"] == "95c6ff3de473786bd98b692375cfdb9cef951668", "base drift")
    for name, bound in accepted["files"].items():
        data = (HERE / "accepted" / name).read_bytes()
        require(len(data) == bound["bytes"] and hashlib.sha256(data).hexdigest() == bound["sha256"], name)
    data = (HERE / "accepted/prototype/diagnostic_server.go.txt").read_bytes()
    require(hashlib.sha256(data).hexdigest() == "987cd212e24c2bd1d4c28ce65501a353aacca6289b48ae3548b7eae39fb14101", "accepted generated bytes drift")
    manifest = json.loads((HERE / "accepted/source/manifest.json").read_text())
    for name, bound in manifest["files"].items():
        require(hashlib.sha256((REPO / name).read_bytes()).hexdigest() == bound["sha256"], "base source drift: " + name)
    workflow = (REPO / ".github/workflows/mongo-profile-prototype.yml").read_text()
    for snippet in ("branches: [codex/mongo-profile-hosted-20261031]", "contents: read", "fetch-depth: 16",
                    "persist-credentials: false", 'go-version: "1.26.10"', "cache: false",
                    "runs-on: ubuntu-24.04", "timeout-minutes: 30", "if: always()"):
        require(snippet in workflow, "workflow contract missing: " + snippet)
    require(not any(trigger in workflow for trigger in ("workflow_dispatch:", "pull_request:", "schedule:", "branches: [main]")), "unselected workflow trigger")
    uses = re.findall(r"uses: ([^\s]+)", workflow)
    require(len(uses) == 3 and all(re.fullmatch(r"actions/(?:checkout|setup-go|upload-artifact)@[0-9a-f]{40}", use) for use in uses), "actions must be pinned")
    driver = (HERE / "run.py").read_text()
    tree = ast.parse(driver)
    constants = {node.targets[0].id: ast.literal_eval(node.value) for node in tree.body
                 if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name)
                 and node.targets[0].id in {"BASE", "ROOT_CHECKPOINT", "ENTRY", "HELPER_ENTRY", "HELPER_TEST", "ORIGINAL", "GENERATED", "HELPER_CASES", "PROFILE", "PINNED_GO"}}
    require(constants["BASE"] == accepted["base"], "driver base drift")
    require(constants["ROOT_CHECKPOINT"] == "dbc659dfee648c11ad105048aa7d007caf8cb097", "retained root checkpoint drift")
    require(all(snippet in driver for snippet in ('ROOT_CHECKPOINT + "^"', 'strip() == BASE',
                '["git", "merge-base", "--is-ancestor", ROOT_CHECKPOINT, sha]',
                'sha == os.environ["GITHUB_SHA"]',
                'root_checkpoint=ROOT_CHECKPOINT, root_checkpoint_parent=BASE',
                '["git", "diff", "--name-only", BASE, sha]')),
            "root ancestry/exact candidate/net diff scope binding missing")
    require(constants["ENTRY"] == "TreeDB/mongo_gateway/server.go", "actual standalone overlay target drift")
    require('write(overlay, {"Replace": {str(runner.base / ENTRY): str(generated)}})' in driver,
            "actual standalone overlay must preserve the original entry mapping")
    require(constants["HELPER_ENTRY"] == "TreeDB/mongo_profile_constructor_probe/server.go" and
            constants["HELPER_TEST"] == "TreeDB/mongo_profile_constructor_probe/hosted_profile_test.go",
            "helper virtual files must share the isolated module-local probe directory")
    require('write(test_overlay, {"Replace": {str(helper_entry_path): str(generated), str(fixture_path): str(fixture)}})' in driver,
            "helper overlay must not contaminate the imported production package")
    require('str(runner.base / ENTRY), str(fixture_path)' not in driver and
            driver.count('str(helper_entry_path), str(fixture_path)], timeout=600)') == 2,
            "both ordinary and race helper file lists must use only the isolated virtual files")
    require('helper_virtual_entry=str(helper_entry_path), helper_virtual_test=str(fixture_path)' in driver,
            "helper virtual source paths must be explicit provenance")
    require('with helper_probe_directory(runner, helper_entry_path.parent):' in driver,
            "helper builds and controls need the checked empty physical cwd")
    execute = next(node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == "execute")
    probe_with = next(node for node in ast.walk(execute) if isinstance(node, ast.With) and
                      isinstance(node.items[0].context_expr, ast.Call) and
                      isinstance(node.items[0].context_expr.func, ast.Name) and
                      node.items[0].context_expr.func.id == "helper_probe_directory")
    probe_body = ast.get_source_segment(driver, probe_with)
    require(all(snippet in probe_body for snippet in ('"build-file-list-tests"', 'for case in HELPER_CASES:',
                '"build-concurrency-race-tests"', '"concurrent-stop-close-race"')),
            "checked cwd must enclose ordinary/race builds and existing controls")
    cleanup = next(node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == "helper_probe_directory")
    cleanup_source = ast.get_source_segment(driver, cleanup)
    for snippet in ('path.mkdir(mode=0o700)', 'not any(path.iterdir())', 'path.rmdir()',
                    'current.st_dev, current.st_ino', 'not path.is_symlink()', 'runner.clean_base()',
                    '"helper-probe-directory.json"', 'receipt["cleanup_error"]'):
        require(snippet in cleanup_source, "checked empty cwd lifecycle missing: " + snippet)
    require(len(next(node for node in cleanup.body if isinstance(node, ast.Try)).finalbody) > 0 and
            'shutil.rmtree' not in cleanup_source and 'unlink(' not in cleanup_source,
            "cwd cleanup must run in finally and never remove unexpected files")
    require('-vet=off' not in driver and '"-vet"' not in driver, "default Go vet must remain enabled")
    require(constants["GENERATED"] == hashlib.sha256(data).hexdigest(), "driver generated hash drift")
    require(constants["ORIGINAL"] == manifest["files"]["TreeDB/mongo_gateway/server.go"]["sha256"], "driver original hash drift")
    require(constants["PROFILE"] == "command_wal_durable", "canonical gateway profile drift")
    require(constants["PINNED_GO"] == "go1.26.10", "pinned Go version drift")
    require(not any(isinstance(node, ast.Constant) and node.value == "durable" for node in ast.walk(tree)),
            "retired durable CLI spelling must not return")
    gateway = next(node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == "gateway")
    launch_args = next(node.value for node in ast.walk(gateway) if isinstance(node, ast.Assign)
                       and any(isinstance(target, ast.Name) and target.id == "args" for target in node.targets))
    require(isinstance(launch_args, ast.List) and isinstance(launch_args.elts[-2], ast.Constant)
            and launch_args.elts[-2].value == "-profile" and isinstance(launch_args.elts[-1], ast.Name)
            and launch_args.elts[-1].id == "PROFILE", "all gateway launches must use the bound canonical profile")
    for snippet in ('opened["profile"] == PROFILE', 'opened["stats"].get("treedb.profile.resolved") == PROFILE',
                    'live.owner(directory, "server", build, PROFILE)', '"GOTOOLDIR", "GOTOOLCHAIN"',
                    'goenv["GOVERSION"] == PINNED_GO', 'Path(goenv["GOROOT"]).resolve(strict=True) == goroot',
                    'tooldir == (goroot / "pkg/tool/linux_amd64").resolve(strict=True)',
                    'compiler_version == selected_compiler_version == "compile version " + PINNED_GO'):
        require(snippet in driver, "profile/toolchain agreement guard missing: " + snippet)
    for check in ('runner.command("compiler-version"', 'runner.command("go-tool-compiler-version"'):
        require(driver.index(check) < driver.index('runner.command("prepare-pinned-dependencies"'),
                "compiler agreement must precede dependency preparation/builds")
    require("RUNNER_TOOL_CACHE" not in driver, "ineffective toolcache environment export returned")
    require(driver.index("runner.stage_toolchain()") < driver.index('runner.command("go-version"'),
            "owned staging must precede all Go execution")
    for snippet in ('TOOLCHAIN_BYTE_CAP = 1024**3', 'TOOLCHAIN_STAGE_SECONDS = 300',
                    'goroot = root / "toolcache" / PINNED_GO', 'stream.readline(256).strip() == PINNED_GO',
                    'guard(info.st_size)', 'guard(len(block))', 'FLOOR + required_bytes',
                    'receipt["copied_bytes"] + info.st_size <= TOOLCHAIN_BYTE_CAP',
                    'staged_hashes == original_hashes', 'write(self.out / "toolchain-stage.json", receipt)',
                    'toolchain_staging=runner.toolchain_stage'):
        require(snippet in driver, "bounded toolchain staging contract missing: " + snippet)
    require('tests = binaries / "profile-helper.test"' in driver and
            'generated_sha256=GENERATED, retained_binary=True' in driver,
            "helper profile ELF must be retained with matching hash")
    for snippet in ('GOTOOLCHAIN="local"', 'GOWORK="off"', 'GOPROXY="off"', 'GOSUMDB="off"',
                    'FLOOR = 8 * 1024**3', '"--detach"', '"--ignored=matching"', '"-mod=readonly"',
                    '"build-actual-standalone"', 'live.owner(', 'live.checkpoint_proof(', 'signal.SIGTERM',
                    '"tool", "pprof"', 'self.guard()', 'os.killpg(', '"GOMAXPROCS"'):
        require(snippet in driver, "driver contract missing: " + snippet)
    require('"GOMAXPROCS"] =' not in driver and 'GOMAXPROCS="' not in driver, "forced runtime CPU setting")
    require('"run",' not in driver and '"bench",' not in driver, "unselected Go entry")
    fixture = (HERE / "hosted_profile_test.go.txt").read_text()
    for case in constants["HELPER_CASES"]:
        direct = '"' + case + '"' in fixture
        response = case.startswith("response-") and 'strings.HasPrefix(which, "response-")' in fixture and '"' + case.removeprefix("response-") + '"' in fixture
        require(direct or response, "helper dispatcher missing: " + case)
    for snippet in ("SYNTHETIC helper-scope owner", 'target = "/x/../start?mode=off"',
                    'method, target = "OPTIONS", "*"', "FlushError() error", "Close escaped admitted Flush"):
        require(snippet in fixture, "source-review regression control missing: " + snippet)
    print(json.dumps(dict(status="offline-source-contracts-passed", copied_packet_files=len(accepted["files"]),
                          helper_cases=len(constants["HELPER_CASES"]), generated_sha256=constants["GENERATED"],
                          go_parse=False, go_build=False, go_runtime=False, pprof_decode=False), indent=2))


if __name__ == "__main__":
    main()
